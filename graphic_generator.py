from PIL import Image, ImageDraw, ImageFont

def create_graphic(headline):

    headline_lower = headline.lower()

    # Default Theme
    bg_color = (10, 15, 35)
    header_color = (0, 102, 255)
    banner_color = (220, 30, 30)
    logo_path = None
    banner_text = "BREAKING NEWS"

    # World Cup Theme
    if "world cup" in headline_lower:
        bg_color = (8, 24, 64)
        header_color = (196, 160, 40)
        banner_color = (196, 160, 40)
        logo_path = "assets/competition_logos/world_cup.png"
        banner_text = "WORLD CUP"

    # Champions League Theme
    elif "champions league" in headline_lower:
        bg_color = (5, 20, 80)
        header_color = (255, 255, 255)
        banner_color = (25, 50, 150)
        logo_path = "assets/competition_logos/champions_league.png"
        banner_text = "CHAMPIONS LEAGUE"

    # Premier League Theme
    elif "premier league" in headline_lower:
        bg_color = (55, 0, 90)
        header_color = (120, 0, 180)
        banner_color = (0, 255, 180)
        logo_path = "assets/competition_logos/premier_league.png"
        banner_text = "PREMIER LEAGUE"

    width = 1080
    height = 1080

    image = Image.new("RGB", (width, height), bg_color)

    draw = ImageDraw.Draw(image)

    title_font = ImageFont.truetype(
        "fonts/Anton-Regular.ttf",
        120
    )

    banner_font = ImageFont.truetype(
        "fonts/Anton-Regular.ttf",
        60
    )

    footer_font = ImageFont.truetype(
        "fonts/Anton-Regular.ttf",
        40
    )

    # Header
    draw.rectangle(
        [(0, 0), (1080, 120)],
        fill=header_color
    )

    draw.text(
        (40, 20),
        "FOOTBALL AI",
        font=banner_font,
        fill=(255, 255, 255)
    )

    # Banner
    draw.rectangle(
        [(40, 170), (650, 260)],
        fill=banner_color
    )

    draw.text(
        (70, 185),
        banner_text,
        font=banner_font,
        fill=(255, 255, 255)
    )

    # Competition Logo
    if logo_path:
        try:
            logo = Image.open(logo_path).convert("RGBA")

            logo.thumbnail((220, 220))

            image.paste(
                logo,
                (820, 140),
                logo
            )
        except:
            pass

    # Headline Split
    words = headline.upper().split()

    lines = []
    current = ""

    for word in words:

        if len(current + " " + word) <= 14:
            current += " " + word
        else:
            lines.append(current.strip())
            current = word

    lines.append(current)

    y = 350

    for line in lines[:4]:

        draw.text(
            (60, y),
            line,
            font=title_font,
            fill=(255, 255, 255)
        )

        y += 130

    # Footer
    draw.line(
        [(60, 900), (1020, 900)],
        fill=(255, 255, 255),
        width=4
    )

    draw.text(
        (60, 940),
        "GENERATED BY FOOTBALL AI",
        font=footer_font,
        fill=(180, 180, 180)
    )

    filename = "static/latest_graphic.png"

    image.save(filename)

    return filename
